def encoded(value):
    return json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":"),
                      sort_keys=True).encode("utf-8")


def parse_json(raw, mutant=None):
    def pairs(entries):
        result = {}
        for key, value in entries:
            need(key not in result or mutant == "duplicate_keys", key, "invalid_json")
            result[key] = value
        return result

    def finite(raw_number):
        value = float(raw_number)
        need(math.isfinite(value) or mutant == "nonfinite", "", "invalid_json")
        return value

    def constant(value):
        raise WireError("invalid_json")

    try:
        return json.loads(raw, object_pairs_hook=pairs, parse_float=finite, parse_constant=constant)
    except (json.JSONDecodeError, UnicodeError, RecursionError):
        raise WireError("invalid_json") from None


def validate(schema, value, request=False, path="", mutant=None):
    name = schema if isinstance(schema, str) else None
    spec = S[schema] if name else schema
    if "nullable" in spec:
        if value is not None:
            validate(spec["nullable"], value, request, path, mutant)
        return
    if "one" in spec:
        matches = 0
        for option in spec["one"]:
            try:
                validate(option, value, request, path, mutant)
            except WireError:
                pass
            else:
                matches += 1
        need(matches == 1, path)
        conditional(name, value, request, path, mutant)
        return
    if "decimal" in spec:
        low, high, pattern = spec["decimal"]
        if request and type(value) is int:
            need(low <= value <= high, path)
            return
        if mutant == "numeric_output" and type(value) is int:
            need(low <= value <= high, path)
            return
        need(isinstance(value, str), path)
        need(len(value) <= 20, path)
        need(re.fullmatch(pattern, value) is not None or mutant == "leading_zero"
             and re.fullmatch(r"-?[0-9]+", value) is not None
             or mutant == "negative_zero" and value == "-0", path)
        need(value != "-0" or mutant == "negative_zero", path)
        need(low <= int(value) <= high or mutant == "integer_overflow", path)
        return
    if "enum" in spec:
        need(any(type(value) is type(item) and value == item for item in spec["enum"]), path)
        return
    kind = spec["type"]
    if kind == "object":
        need(isinstance(value, dict), path)
        if "map" in spec:
            need(len(value) <= spec["max"] or mutant == "metadata_count", path)
            for key, item in value.items():
                need(isinstance(key, str), path)
                validate(spec["map"], item, request, path + "." + key, mutant)
        else:
            need(set(spec["required"]) <= value.keys() or mutant == "required", path)
            need(value.keys() <= spec["properties"].keys() or mutant == "unknown_fields", path)
            for key, item in value.items():
                if key in spec["properties"]:
                    validate(spec["properties"][key], item, request, path + "." + key, mutant)
    elif kind == "array":
        need(isinstance(value, list), path)
        need(spec["min"] <= len(value), path)
        need(spec["max"] is None or len(value) <= spec["max"]
             or mutant == "candidate_ceiling" and path.endswith(".candidates"), path)
        for index, item in enumerate(value):
            validate(spec["items"], item, request, f"{path}[{index}]", mutant)
    elif kind == "string":
        need(isinstance(value, str), path)
        try:
            size = len(value) if mutant == "utf8_codepoints" else len(value.encode("utf-8"))
        except UnicodeEncodeError:
            raise WireError("invalid_input", path) from None
        cap = spec["max"]
        if mutant == "content_cap" and path.endswith(".content"):
            cap = 4097
        if mutant == "metadata_string" and path.endswith(".value"):
            cap = 4097
        need(spec["min"] <= size and (cap is None or size <= cap), path)
        need(spec["pattern"] is None or re.fullmatch(spec["pattern"], value) is not None, path)
        if name == "Key":
            need(mutant == "control_keys" or all(unicodedata.category(c) != "Cc" for c in value), path)
    elif kind == "boolean":
        need(type(value) is bool, path)
    else:
        if kind == "integer" and mutant == "bool_integer" and type(value) is bool:
            return
        need(type(value) is int if kind == "integer" else type(value) in (int, float), path)
        try:
            finite = math.isfinite(value)
        except OverflowError:
            finite = False
        need(finite or mutant == "nonfinite", path)
        high = spec["max"]
        if mutant == "candidate_ceiling" and path.endswith(".candidates"):
            high = 1001
        if mutant == "deadline_ceiling" and path.endswith(".deadline_ms"):
            high = 5001
        need(spec["min"] is None or value >= spec["min"], path)
        need(high is None or value <= high, path)
        need(not spec.get("positive") or value > 0, path)
    conditional(name, value, request, path, mutant)


def distinct(values, field):
    need(len({encoded(value) for value in values}) == len(values), field)


def conditional(name, value, request, path, mutant):
    if name in ("Scope", "EffectiveScope"):
        need("session" not in value or "user" in value or mutant == "session_user", path)
    elif name == "Interval":
        low, high = value["valid_from_ms"], value["valid_to_ms"]
        need(low is None or high is None or int(low) < int(high), path)
    elif name == "Condition":
        need(("value" not in value) if value["op"] == "exists" else ("value" in value), path)
        need(value["op"] not in ("lt", "lte", "gt", "gte")
             or value["value"]["type"] in ("string", "integer", "float"), path)
    elif name == "Filter":
        need(len(value.get("all", [])) + len(value.get("any", [])) <= 64, path)
    elif name == "Item":
        need((value["kind"] in ("fact", "relation")) == ("assertion" in value), path)
        need(value.get("merge", "none") != "merge_provenance"
             or "revision" in value.get("expected", {}), path)
        entries = value.get("provenance", [value["source"]])
        logical = [{"source": e["source_id"], "kind": e["source_kind"],
                    **({"uri": e["uri"]} if "uri" in e else {}),
                    **({"transformation": e["transformation_id"]} if "transformation_id" in e else {})}
                   for e in entries]
        need(encoded_provenance_bytes(logical) <= 4096, path + ".provenance")
    elif name == "Ranking":
        weights = value.get("weights", [1, 0, 0])
        need(abs(sum(Fraction(str(w)) for w in weights) - 1) <= Fraction(1, 10**12)
             or mutant == "weight_sum", path + ".weights")
        need(weights[1] == 0 or "half_life_ms" in value or mutant == "decay_half_life", path)
    elif name in ("Evidence", "RecallRequest") and "vector" in value:
        for component in value["vector"]:
            try:
                rounded = struct.unpack(">f", struct.pack(">f", component))[0]
            except (OverflowError, struct.error):
                raise WireError("invalid_input", path + ".vector") from None
            need(math.isfinite(rounded), path + ".vector")
    if name == "Evidence" and "payload_base64" in value:
        try:
            payload = base64.b64decode(value["payload_base64"], validate=True)
        except (binascii.Error, ValueError):
            raise WireError("invalid_input", path + ".payload_base64") from None
        need(len(payload) <= 1048576, path + ".payload_base64")
    if name == "RecallRequest":
        need("vector" in value or "text" in value or bool(value.get("entity_seeds")), path)
        need("embedding_provider" not in value or "text" in value and "vector" not in value, path)
        scopes = value.get("scopes", [value["scope"]])
        distinct(scopes, path + ".scopes")
        need(value["scope"] in scopes, path + ".scopes")
        if "kinds" in value:
            need(bool(value["kinds"]), path + ".kinds")
            distinct(value["kinds"], path + ".kinds")
        cap = value.get("limits", {}).get("candidates", 200)
        need(value.get("limit", 20) <= cap or mutant == "limit_candidates", path + ".limit")
    elif name == "FactsRequest":
        need(not value.get("history", False) or "as_of_ms" not in value, path)
    elif name == "CorrectionRequest":
        action = value["action"]
        if action == "remove":
            need(not {"at_ms", "replacement", "correction_interval"}.intersection(value), path)
        else:
            need(("at_ms" in value) != ("correction_interval" in value), path)
            need(action != "close" or "correction_interval" not in value, path)
            need(("replacement" in value) == (action == "replace"), path)
            if "replacement" in value:
                need(value["replacement"]["kind"] in ("fact", "relation"), path)
    elif name == "ForgetRequest":
        need(("expires_at_ms" in value) == (value["mode"] == "expire"), path)
        need("session" not in value["target"] or "session" in value["scope"], path)
        if "ids" in value["target"]:
            distinct([r["id"] for r in value["target"]["ids"]], path + ".target")
            need(all(int(r["revision"]) > 0 for r in value["target"]["ids"]), path + ".target")
        for field in ("series", "entity"):
            if field in value["target"]:
                need(int(value["target"][field]["revision"]) > 0, path + ".target")
    elif name in ("RememberRequest", "ConsolidateRequest"):
        items = value["items"] if name == "RememberRequest" else [value["output"]]
        distinct([item["id"] for item in items], path)
        cap = value.get("max_references", 64)
        for item in items:
            need(len(item.get("references", [])) <= cap, path + ".references")
        if name == "ConsolidateRequest":
            distinct([r["id"] for r in value["inputs"]], path + ".inputs")
            need(len(value["inputs"]) <= min(cap, 64) or mutant == "consolidation_cap", path + ".inputs")
            need(all(int(r["revision"]) > 0 for r in value["inputs"]), path + ".inputs")
            need(value["output"]["kind"] == "episodic"
                 and "transformation_id" in value["output"]["source"], path + ".output")
    elif name == "ReadMeta":
        for field in ("truncation", "limitations"):
            need(value[field] == sorted(set(value[field])), path + "." + field)
        need("retained_state_only" in value["limitations"] or mutant == "retained_limitation", path)
        need(value["complete"] or bool(value["truncation"]), path)
    elif name == "ReceiptResponse":
        need(value["result"]["replayed"] is True or mutant == "receipt_replayed", path)
    elif name in ("Ref", "Input", "Expected", "ResumeRequest"):
        if "revision" in value:
            need(int(value["revision"]) > 0 or request and name == "Ref", path + ".revision")
        if "generation" in value:
            need(int(value["generation"]) > 0, path + ".generation")
    elif name == "Erasure":
        need(value["state"] == "pending" or "resume_token" not in value, path)
        need(int(value["revision"]) > 0 and int(value["generation"]) > 0, path)


def validate_response(operation, status, body, request=None, mutant=None):
    need(operation in OPERATIONS, "operation")
    need(type(status) is int and isinstance(body, dict), "response")
    if status >= 400:
        validate("Error", body, mutant=mutant)
        code = body["error"]["code"]
        allowed = (400, 413, 415, 422) if code == "invalid_json" else (ERROR_STATUS.get(code),)
        need(status in allowed or mutant == "error_status", "status")
        return
    need(status == 200 or status == 202 and operation in ("forget", "resume_erasure"), "status")
    schema = OPERATIONS[operation][3]
    if operation == "consolidate" and body.get("dry_run") is True:
        schema = "PlanResponse"
    validate(schema, body, mutant=mutant)
    result = body.get("result", body)
    if schema == "MutationResponse" or operation == "receipt":
        op = result["receipt"]["operation"]
        need(operation == "receipt" or op == operation, "receipt.operation")
        if op in ("forget", "resume_erasure"):
            need("erasure_notice" in result or mutant == "erasure_notice", "erasure_notice")
            need("state" in result, "state")
            pending = result["state"] == "pending"
            need(operation == "receipt" or (status == 202) == pending, "status")
            if "erasure_notice" in result:
                expiry = result["state"] == "retention_set"
                need(("manifest_id" not in result["erasure_notice"]) if expiry else
                     ("manifest_id" in result["erasure_notice"]), "erasure_notice.manifest_id")
        else:
            need(not {"state", "erasure", "erasure_notice"}.intersection(result), "state")
    if request and schema in ("RecallResponse", "FactsResponse"):
        meta = body["meta"]
        need("as_of_ms" not in request or "historical_candidate_discovery_not_exhaustive"
             in meta["limitations"] or mutant == "historical_limitation", "meta.limitations")
        need(meta["complete"] or request.get("allow_partial", False), "meta.complete")


def validate_response_headers(status, headers):
    need(type(status) is int and isinstance(headers, dict), "headers")
    need(all(isinstance(k, str) and isinstance(v, str) for k, v in headers.items()), "headers")
    lowered = {k.lower(): v for k, v in headers.items()}
    need(len(lowered) == len(headers), "headers")
    need(status != 429 or lowered.get("retry-after") == "1", "Retry-After")


def validate_http(operation, request, mutant=None):
    need(operation in OPERATIONS, "operation")
    need(request.keys() == {"method", "path", "headers", "body"}, "http")
    need(request["method"] == "POST" or mutant == "http_method", "method")
    match = re.fullmatch(r"/v1/memory/([^/]+)/" + re.escape(OPERATIONS[operation][0]), request["path"])
    need(match is not None, "path")
    validate("Binding", match.group(1), True, "binding", mutant)
    headers = request["headers"]
    need(isinstance(headers, dict) and all(isinstance(k, str) and isinstance(v, str)
                                         for k, v in headers.items()), "headers")
    lowered = {k.lower(): v for k, v in headers.items()}
    need(len(lowered) == len(headers), "headers")
    # Unknown HTTP headers are not JSON fields. They never supply a scope or key.
    body = request["body"]
    raw_size = len(body.encode("utf-8")) if isinstance(body, str) else len(encoded(body))
    if raw_size > 8388608:
        raise WireError("invalid_json", "body", 413)
    if isinstance(body, str):
        body = parse_json(body, mutant)
    validate(OPERATIONS[operation][2], body, True, "", mutant)
    return body


