def self_test():
    cli_path = Path(__file__).parent / "fixtures" / "memory_cli" / "exchanges.json"
    cli_exchanges = parse_json(cli_path.read_text(encoding="utf-8"))
    for exchange in cli_exchanges:
        validate_response(exchange["verb"].replace("-", "_"), exchange["status"],
                          parse_json(exchange["stdout"]), request=exchange["request"])
    mcp_path = Path(__file__).parent / "fixtures" / "memory_tools" / "exchanges.json"
    mcp_exchanges = parse_json(mcp_path.read_text(encoding="utf-8"))
    for exchange in mcp_exchanges["cases"]:
        operation = exchange["name"].removeprefix("vlite_memory_")
        status = 202 if operation == "resume_erasure" else 200
        validate_response(operation, status, exchange["response"], request=exchange["request"])
    cases, structural = [], []
    for path in sorted(ROOT.glob("*.json")):
        fixture = parse_json(path.read_text(encoding="utf-8"))
        verify(fixture["schema"] == "memory-rest-wire-v1", str(path))
        verify(path.stem in OPERATIONS and fixture["operation_id"] == OPERATIONS[path.stem][1],
               "wrong operation id in " + str(path))
        cases.extend(fixture["cases"])
        structural.extend(fixture.get("structural", []))
    verify(bool(cases), "no wire goldens")
    verify(len({case["name"] for case in cases}) == len(cases), "duplicate case name")
    verify(len({case["name"] for case in structural}) == len(structural), "duplicate structural name")
    repairs, second = 0, 0
    for case in cases:
        run_case(case)
        rejected = case["expected"]["status"] >= 400
        verify(rejected == ("defect" in case), case["name"] + ": missing/extra defect")
        if rejected:
            fixed = copy.deepcopy(case)
            edit(fixed, case["defect"])
            if case.get("repair_check") == "gate":
                body = validate_http(fixed["operation"], expand_input(fixed["request"]))
                authorize(fixed["operation"], body, expand_input(fixed["view"]))
                capability_gate(fixed["operation"], body, expand_input(fixed["view"]))
            elif case.get("repair_check") == "structure":
                validate_http(fixed["operation"], expand_input(fixed["request"]))
            else:
                result = run_case(fixed, check=False)
                verify(result["status"] < 400, case["name"] + ": repair left " + repr(result))
            repairs += 1
            # A second, orthogonal malformed input must still fail after repair.
            injected = copy.deepcopy(fixed)
            injected["request"] = expand_input(injected["request"])
            if isinstance(injected["request"]["body"], str):
                injected["request"]["body"] = parse_json(injected["request"]["body"])
            injected["request"]["body"]["wire_unexpected"] = True
            result = run_case(injected, check=False)
            verify(result["status"] == 422 and result["body"]["error"]["code"] == "invalid_input",
                   case["name"] + ": second defect escaped")
            second += 1
    for case in structural:
        verify(structural_matches(case), case["name"] + ": wrong structural outcome")
        verify(case["valid"] == ("defect" not in case), case["name"] + ": missing/extra defect")
        if not case["valid"]:
            fixed = copy.deepcopy(case)
            edit(fixed, case["defect"])
            fixed["valid"] = True
            verify(structural_matches(fixed), case["name"] + ": structural repair failed")
            repairs += 1
    by_name = {c["name"]: c for c in cases}
    schemas = {c["name"]: c for c in structural}
    killed = []
    for mutant, (kind, name) in MUTATIONS.items():
        if kind == "structure":
            verify(name in schemas, "mutation has no named specimen: " + name)
            detected = not structural_matches(schemas[name], mutant)
        else:
            verify(name in by_name, "mutation has no named exchange: " + name)
            actual = run_case(by_name[name], mutant, check=False)
            detected = not matches(actual, by_name[name]["expected"])
        verify(detected, "surviving mutation: " + mutant + " at " + name)
        killed.append(mutant)
    print(f"PASS wire: {len(cases)} static exchanges; {len(structural)} structural cases; "
          f"{repairs} single-defect repairs; {second} second defects; "
          f"{len(killed)}/{len(MUTATIONS)} intended mutants killed; 0 survivors")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    try:
        if args.self_test:
            self_test()
        else:
            case = parse_json(sys.stdin.read())
            print(json.dumps(evaluate(case["operation"], case["request"], case["view"]),
                             ensure_ascii=True, allow_nan=False))
    except (ValueError, KeyError, TypeError, AssertionError, OSError) as error:
        print("FAIL: " + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
