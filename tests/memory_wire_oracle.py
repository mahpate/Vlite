def semantic_request(operation, body):
    """Logical equality only; never a production digest, receipt key or hash."""
    result = copy.deepcopy(body)
    result.pop("deadline_ms", None)
    result.pop("require_complete_feed", None)
    result.pop("max_references", None)
    items = result.get("items", [result["output"]] if "output" in result else [])
    for item in items:
        for name, default in (("importance", 0.5), ("provenance", [item["source"]]),
                              ("references", []), ("evidence", []), ("metadata", {}),
                              ("expected", {"absent": True}), ("merge", "none")):
            item.setdefault(name, default)
    if operation == "consolidate":
        result.setdefault("dry_run", False)
        for item in result["inputs"]:
            item.setdefault("disposition", "retain")
        result["inputs"].sort(key=lambda item: item["id"].encode("utf-8"))

    def typed(value):
        if isinstance(value, dict):
            integers = {"revision", "generation", "record", "observed_at_ms", "expires_at_ms",
                        "as_of_ms", "at_ms", "slot_revision", "valid_from_ms", "valid_to_ms"}
            return {k: int(v) if k in integers and v is not None else typed(v) for k, v in value.items()}
        if isinstance(value, list):
            return [typed(item) for item in value]
        return value

    return typed(result)


def retained_receipt(operation, body, view, mutant=None, lookup_only=False):
    for receipt in view.get("receipts", []):
        identity = (receipt["operation"] == operation and receipt["scope"] == effective(body["scope"], view)
                    and receipt["key"] == body["idempotency_key"])
        if identity and (view["clock_ms"] < receipt["retry_until_ms"]
                         or mutant == "receipt_expiry_inclusive"
                         and view["clock_ms"] == receipt["retry_until_ms"]):
            if not lookup_only:
                need(semantic_request(operation, body) == semantic_request(operation, receipt["request"])
                     or mutant == "idempotency_conflict", "", "idempotency_conflict")
            result = copy.deepcopy(receipt["result"])
            result["replayed"] = mutant != "replay_flag"
            return result
    return None


def make_result(operation, scope, outcomes, view):
    return {"receipt": {"id": view["next_receipt_id"], "operation": operation,
                        "scope": effective(scope, view), "sequence": str(view["sequence"] + 1),
                        "retry_until_ms": str(view["clock_ms"] + view["receipt_window_ms"]),
                        "digest_version": "memory-request-v1"},
            "replayed": False, "outcomes": outcomes, "feed": copy.deepcopy(FEED), "remaining_work": "0"}


def logical_item(item):
    source = item["source"]
    result = {"id": item["id"], "kind": item["kind"], "content": item["content"],
              "observed_at": int(item["observed_at_ms"]), "source": source["source_id"],
              "importance": item.get("importance", 0.5),
              "references": [ref["id"] for ref in item.get("references", [])],
              "provenance": [{"source": p["source_id"], "kind": p["source_kind"],
                              **({"uri": p["uri"]} if "uri" in p else {}),
                              **({"transformation": p["transformation_id"]}
                                 if "transformation_id" in p else {})}
                             for p in item.get("provenance", [source])]}
    if "expires_at_ms" in item:
        result["expiry"] = int(item["expires_at_ms"])
    if item.get("merge") == "merge_provenance":
        result["merge_into"] = item["id"]
        result["expected_revision"] = int(item["expected"]["revision"])
    return result


