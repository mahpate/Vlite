"""Independent reference for the persisted agent-memory binding record.

Source: docs/projects/roadmap/m71-memory-followups.md section 1.1 (written
before the Rust code). Python standard library only; nothing is copied from or
generated by Rust. It derives the record of a bindings-file entry, the grants
digest and the strict decoder verdicts, and checks them against the literal
goldens in tests/fixtures/agent_memory/binding_record_golden.json, which the
Rust tests replay.

Run python tests/memory_binding_record_oracle.py --self-test (also with -O).
Without --self-test, stdin is a bindings-file entry and stdout its record.
"""

import argparse
import copy
import hashlib
import json
from pathlib import Path
import re
import struct
import sys


FIXTURE = Path(__file__).parent / "fixtures" / "agent_memory" / "binding_record_golden.json"
KEY = "binding:v1"
LABEL = "VliteMemoryBinding"
RECORD_SCHEMA = "memory-binding-record:v1"
SCHEMA, RANKING, DIGEST = "memory-schema-v1", "memory-ranking-v1", "memory-request-v1"
DOMAIN = b"vlite.memory.binding.grants.v1\0"
MAX_GENERATION, MAX_WINDOW, MAX_STRING = 2**63 - 1, 2_592_000_000, 4096
REQUIRED = ("record_schema", "tenant", "binding", "generation", "state", "graph",
            "memory_schema", "ranking_version", "request_digest_version",
            "receipt_window_ms", "grants_digest")
MUTANT = None


class Malformed(ValueError):
    pass


def need(condition, reason):
    if not condition:
        raise Malformed(reason)


def verify(condition, reason):
    if not condition:
        raise AssertionError(reason)


def frame(value):
    raw = value.encode("utf-8")
    return struct.pack(">I", len(raw)) + raw


def scope_bytes(tenant, scope):
    out = b"scope:v1"
    for value in (tenant, scope["agent"], scope.get("user"), scope.get("session")):
        out += b"\0" if value is None else b"\1" + frame(value)
    return out


def grants_digest(tenant, grants):
    out = DOMAIN + struct.pack(">I", len(grants))
    for grant in grants:
        out += frame(grant["principal"])
        out += b"\1" if grant.get("raw_access", False) else b"\0"
        out += struct.pack(">I", len(grant["scopes"]))
        for scope in grant["scopes"]:
            encoded = scope_bytes(tenant, scope)
            out += struct.pack(">I", len(encoded)) + encoded
    if MUTANT == "digest_unframed_scopes":
        out = out.replace(b"\0\0\0", b"")
    return "v1:" + hashlib.sha256(out).hexdigest()


def stored(tenant, name):
    return name if tenant == "@root" else f"t{tenant}__{name}"


def record_properties(entry):
    grants = entry["grants"]
    if MUTANT == "digest_sorted_grants":
        grants = sorted(grants, key=lambda grant: grant["principal"])
    properties = {
        "record_schema": RECORD_SCHEMA,
        "tenant": entry["tenant"],
        "binding": entry["binding"],
        "generation": str(entry["generation"]),
        "state": entry["state"],
        "graph": entry["graph"],
        "memory_schema": entry["schema_version"],
        "ranking_version": entry["ranking_version"],
        "request_digest_version": entry["digest_version"],
        "receipt_window_ms": str(entry["receipt_window_ms"]),
        "grants_digest": grants_digest(entry["tenant"], grants),
    }
    if entry["state"] == "retired":
        properties["retired_at_ms"] = str(entry["retired_at_ms"])
    if entry["evidence_collection"] is not None:
        properties["evidence"] = entry["evidence_collection"]
    return properties


def canonical(value, low, high):
    need(isinstance(value, str) and re.fullmatch(r"[0-9]{1,20}", value) is not None
         and (value == "0" or not value.startswith("0")), "noncanonical decimal")
    number = int(value)
    need(low <= number <= high, "decimal out of range")
    return number


def collection_name(value):
    return isinstance(value, str) and re.fullmatch(r"[a-z][a-z0-9_-]{0,62}", value) is not None


def tenant_qualified(value):
    return re.fullmatch(r"t[0-9a-f]{32}__.+", value) is not None


def decode(node, holder):
    """The strict decoder: raises Malformed unless `node` is exactly a record."""
    need(node["labels"] == [LABEL], "labels")
    need(node.get("expires_at_ms") is None, "expiry")
    properties = node["properties"]
    need(all(isinstance(value, str) and len(value.encode("utf-8")) <= MAX_STRING
             for value in properties.values()), "property type or size")
    names = set(properties)
    optional = {"retired_at_ms", "evidence"}
    need(set(REQUIRED) <= names <= set(REQUIRED) | optional, "property names")
    need(properties["record_schema"] == RECORD_SCHEMA, "record schema")
    need(properties["memory_schema"] == SCHEMA, "memory schema")
    need(properties["ranking_version"] == RANKING, "ranking version")
    need(properties["request_digest_version"] == DIGEST, "digest version")
    tenant = properties["tenant"]
    need(tenant == "@root" or re.fullmatch(r"[0-9a-f]{32}", tenant) is not None, "tenant")
    need(collection_name(properties["binding"]), "binding name")
    graph = properties["graph"]
    need(collection_name(graph) and not tenant_qualified(graph), "graph name")
    if "evidence" in properties:
        evidence = properties["evidence"]
        need(collection_name(evidence) and evidence != "default"
             and not tenant_qualified(evidence), "evidence name")
    generation = canonical(properties["generation"], 1, MAX_GENERATION)
    window = canonical(properties["receipt_window_ms"], 1, MAX_WINDOW)
    need(properties["state"] in ("active", "retired"), "state")
    if properties["state"] == "retired":
        need("retired_at_ms" in properties, "retired without time")
        canonical(properties["retired_at_ms"], 1, 2**64 - 1)
    else:
        need("retired_at_ms" not in properties, "active with retirement time")
    need(re.fullmatch(r"v1:[0-9a-f]{64}", properties["grants_digest"]) is not None, "digest")
    need(stored(tenant, graph) == holder, "record held by another graph")
    return {"generation": generation, "window": window}


def self_test():
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    verify(fixture["key"] == KEY and fixture["label"] == LABEL, "key and label")
    names = set()
    digests = {}
    for case in fixture["records"]:
        verify(case["name"] not in names, "duplicate case " + case["name"])
        names.add(case["name"])
        derived = record_properties(case["entry"])
        verify(derived == case["expected"]["properties"], "record " + case["name"])
        holder = stored(case["entry"]["tenant"], case["entry"]["graph"])
        verify(case["expected"]["holder"] == holder, "holder " + case["name"])
        node = {"labels": [LABEL], "properties": derived, "expires_at_ms": None}
        decode(node, holder)
        digests[case["name"]] = derived["grants_digest"]
    verify(digests["two-grants-reordered"] != digests["two-grants-in-order"], "order matters")
    verify(digests["grants-raw-access"] != digests["grants-plain"], "raw access matters")
    verify(digests["scope-with-session"] != digests["scope-agent-only"], "scopes matter")
    verify(len(set(digests.values())) == len(digests), "all digests distinct")
    for case in fixture["malformed"]:
        try:
            decode(copy.deepcopy(case["node"]), case["holder"])
        except Malformed:
            continue
        raise AssertionError("accepted malformed case " + case["name"])
    verify(len(fixture["malformed"]) >= 40, "malformed catalog is complete")
    # The goldens must be sensitive to each intended defect of this reference.
    global MUTANT
    for mutant in ("digest_unframed_scopes", "digest_sorted_grants"):
        MUTANT = mutant
        changed = [case["name"] for case in fixture["records"]
                   if record_properties(case["entry"]) != case["expected"]["properties"]]
        MUTANT = None
        verify(changed, "mutant survived " + mutant)
    print("memory binding record oracle: self-test passed "
          f"({len(fixture['records'])} records, {len(fixture['malformed'])} malformed)")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    arguments = parser.parse_args()
    if arguments.self_test:
        self_test()
        return 0
    entry = json.load(sys.stdin)
    json.dump(record_properties(entry), sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
