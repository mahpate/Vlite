#!/usr/bin/env python3
"""DO-001 graph-file marker compatibility probe (feature-agent-graph ITEM-007).

Subcommands
-----------
fixtures
    Writes the deterministic graph-compatibility fixtures (hex text) and a
    SHA-256 manifest of their decoded bytes to tests/fixtures/graph_compat/.
    The encoder here is independent of the Rust one in tests/graph_compat.rs;
    that test asserts both agree byte for byte.

run [--revs REV ...] [--work DIR] [--skip-bindings] [--json PATH]
    For HEAD-default and every release tag: extracts the exact revision with
    `git archive` into an isolated directory, builds a throwaway probe crate
    against it OFFLINE into a per-revision target directory (no global
    installs, nothing fetched), runs every REQ-055 library entry point that
    exists in that revision against each graph-flagged fixture, and (unless
    --skip-bindings) opens the fixtures through that revision's C ABI via the
    Python binding and, where an offline node-gyp build is possible, through
    the Node binding. Prints a table compared with the DO-001 expectations
    and exits non-zero if any expectation fails or any build is unavailable.

Nothing in the working tree is modified by `run`. Uses only the Python
standard library, git, cargo, and (optionally) node.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import struct
import subprocess
import sys
import tarfile
import tempfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE_DIR = ROOT / "tests" / "fixtures" / "graph_compat"
PROBE_TEMPLATE = ROOT / "scripts" / "graph_compat_probe.rs"
DEFAULT_REVS = [
    "81ff901",
    "v0.1.0",
    "v0.1.1",
    "v0.1.2",
    "v0.2.0",
    "v0.3.0",
    "v0.4.0",
]
PRE_V5_REVS = {"v0.1.0", "v0.1.1", "v0.1.2", "v0.2.0"}

# Fixture constants (mirrored in tests/graph_compat.rs).
DIMS = 2
LINEAGE = 0x4752_4150_4801_0001
RECORD_ID = 7
VECTOR = (1.0, 2.0)
PAYLOAD = b"probe"
T0_MS = 1_700_000_000_000
KEY = bytes([0x42]) * 32
FLAG_ENCRYPTED, FLAG_TIMESTAMPS, FLAG_GRAPH = 1, 2, 4
OP_PUT, OP_TIME_ANCHOR, OP_GRAPH = 1, 11, 12
GRAPH_BODY_VERSION, TAG_CREATE_GRAPH = 1, 1


def crc32(data: bytes) -> int:
    return zlib.crc32(data) & 0xFFFFFFFF


def header_v5(flags: int) -> bytes:
    head = b"VLITEDB\0" + struct.pack("<IIQHH", 5, DIMS, LINEAGE, 0, flags)
    return head + struct.pack("<I", crc32(head))


def set_header_flags(data: bytes, flags: int) -> bytes:
    head = data[:26] + struct.pack("<H", flags)
    return head + struct.pack("<I", crc32(head)) + data[32:]


def frame(op: int, sequence: int, record_id: int, count: int, payload_len: int, body: bytes) -> bytes:
    prefix = b"VREC" + struct.pack("<BHBQQII", op, 0, 0, sequence, record_id, count, payload_len)
    prefix += struct.pack("<I", crc32(prefix))
    data = prefix + body
    return data + b"VCMT" + struct.pack("<IQ", crc32(data), sequence)


def put_frame(sequence: int) -> bytes:
    body = struct.pack("<2f", *VECTOR) + PAYLOAD
    return frame(OP_PUT, sequence, RECORD_ID, DIMS, len(PAYLOAD), body)


def anchor_frame(next_sequence: int, timestamp_ms: int) -> bytes:
    return frame(OP_TIME_ANCHOR, next_sequence, 0, 0, 8, struct.pack("<Q", timestamp_ms))


def graph_frame(sequence: int) -> bytes:
    """DO-003 draft: body header + one CreateGraph entry for graph 1 "g"."""
    name = b"g"
    entry_payload = bytes([len(name)]) + name
    entry = struct.pack("<BBHI", TAG_CREATE_GRAPH, 0, 0, len(entry_payload)) + entry_payload
    body = struct.pack("<BBH", GRAPH_BODY_VERSION, 0, 1) + entry
    return frame(OP_GRAPH, sequence, 0, 1, len(body), body)


def fixtures() -> dict[str, bytes]:
    control_plain = header_v5(0) + put_frame(1)
    return {
        "v5_graph_plain": header_v5(FLAG_GRAPH) + put_frame(1) + graph_frame(2),
        "v5_graph_timestamps": header_v5(FLAG_TIMESTAMPS | FLAG_GRAPH)
        + anchor_frame(1, T0_MS)
        + put_frame(1)
        + anchor_frame(2, T0_MS + 1)
        + graph_frame(2),
        "v5_control_plain": control_plain,
        "v5_control_timestamps": header_v5(FLAG_TIMESTAMPS) + anchor_frame(1, T0_MS) + put_frame(1),
        "v5_control_op12_without_flag": control_plain + graph_frame(2),
    }


def write_fixtures() -> None:
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    manifest = []
    for name, data in sorted(fixtures().items()):
        (FIXTURE_DIR / f"{name}.hex").write_text(data.hex() + "\n", encoding="ascii", newline="\n")
        manifest.append(f"{hashlib.sha256(data).hexdigest()}  {name}.hex")
    (FIXTURE_DIR / "MANIFEST.sha256").write_text(
        "# SHA-256 of the DECODED bytes of each .hex file (hex text is whitespace-insensitive).\n"
        "# Generated by: python scripts/graph_compat_check.py fixtures\n" + "\n".join(manifest) + "\n",
        encoding="ascii",
        newline="\n",
    )
    print(f"wrote {len(manifest)} fixtures to {FIXTURE_DIR}")


# ---------------------------------------------------------------------------
# Isolated revision builds.
# ---------------------------------------------------------------------------


def run_cmd(args: list[str], cwd: Path | None = None, env: dict | None = None, check: bool = True) -> subprocess.CompletedProcess:
    if env is not None and not os.path.dirname(str(args[0])):
        found = shutil.which(str(args[0]), path=env.get("PATH"))
        if found:
            args = [found] + list(args[1:])
    result = subprocess.run(args, cwd=cwd, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if check and result.returncode != 0:
        raise RuntimeError(f"{' '.join(map(str, args))} failed ({result.returncode}):\n{result.stdout[-4000:]}\n{result.stderr[-4000:]}")
    return result


def resolve(rev: str) -> str:
    return run_cmd(["git", "rev-parse", "--verify", f"{rev}^{{commit}}"], cwd=ROOT).stdout.strip()


def extract(rev: str, sha: str, work: Path) -> Path:
    """`git archive` of the exact commit; never the working tree."""
    source = work / f"src-{rev}"
    stamp = source / ".vlite-archive-sha"
    if stamp.is_file() and stamp.read_text().strip() == sha:
        return source
    if source.exists():
        shutil.rmtree(source)
    source.mkdir(parents=True)
    archive = work / f"{rev}.tar"
    with archive.open("wb") as handle:
        subprocess.run(["git", "archive", "--format=tar", sha], cwd=ROOT, stdout=handle, check=True)
    with tarfile.open(archive) as tar:
        tar.extractall(source, filter="data")
    archive.unlink()
    stamp.write_text(sha + "\n")
    return source


def source_text(source: Path) -> str:
    return "\n".join(path.read_text(encoding="utf-8", errors="replace") for path in sorted((source / "src").rglob("*.rs")))


BLOCK = re.compile(r"^\s*// @block (?P<symbols>.+?)\s*$")
END = re.compile(r"^\s*// @end\s*$")


def render_probe(text: str) -> tuple[str, list[str]]:
    """Keeps blocks whose every `|`-separated symbol occurs in the revision source."""
    output, dropped, keep = [], [], True
    for line in PROBE_TEMPLATE.read_text(encoding="utf-8").splitlines():
        match = BLOCK.match(line)
        if match:
            symbols = [symbol.strip() for symbol in match["symbols"].split("|")]
            keep = all(symbol in text for symbol in symbols)
            if not keep:
                dropped.append(match["symbols"])
            continue
        if END.match(line):
            keep = True
            continue
        if keep:
            output.append(line)
    return "\n".join(output) + "\n", dropped


def cargo_env() -> dict:
    env = dict(os.environ)
    cargo_bin = Path.home() / ".cargo" / "bin"
    env["PATH"] = f"{cargo_bin}{os.pathsep}{env.get('PATH', '')}"
    env["CARGO_NET_OFFLINE"] = "true"
    return env


def build_probe(rev: str, source: Path, work: Path) -> tuple[Path, list[str]]:
    crate = work / f"probe-{rev}"
    (crate / "src").mkdir(parents=True, exist_ok=True)
    text, dropped = render_probe(source_text(source))
    (crate / "src" / "main.rs").write_text(text, encoding="utf-8")
    dependency = source.as_posix()
    (crate / "Cargo.toml").write_text(
        "[package]\nname = \"graph-compat-probe\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n"
        f"[dependencies]\nvlite = {{ path = \"{dependency}\", default-features = false }}\n\n[workspace]\n",
        encoding="utf-8",
    )
    # Pin third-party versions to the revision's own lockfile; offline only.
    shutil.copyfile(source / "Cargo.lock", crate / "Cargo.lock")
    target = work / f"target-{rev}"
    run_cmd(["cargo", "build", "--offline", "--quiet", "--target-dir", str(target)], cwd=crate, env=cargo_env())
    exe = target / "debug" / ("graph-compat-probe.exe" if os.name == "nt" else "graph-compat-probe")
    return exe, dropped


def build_ffi(rev: str, source: Path, work: Path) -> Path:
    target = work / f"target-{rev}"
    run_cmd(["cargo", "build", "--offline", "--locked", "--quiet", "-p", "vlite-ffi", "--target-dir", str(target)], cwd=source, env=cargo_env())
    name = {"nt": "vlite_ffi.dll"}.get(os.name, "libvlite_ffi.dylib" if sys.platform == "darwin" else "libvlite_ffi.so")
    return target / "debug" / name


PY_PROBE = r"""
import json, sys
sys.path.insert(0, sys.argv[1])
from vlite_embedded import NativeLibrary, EmbeddedError
import inspect
lib = NativeLibrary(sys.argv[2])
key = bytes.fromhex(sys.argv[3])
for spec in sys.argv[4:]:
    name, path = spec.split("=", 1)
    calls = [("python NativeLibrary.open", lambda: lib.open(path))]
    if "key" in inspect.signature(lib.open).parameters:
        calls.append(("python NativeLibrary.open(key)", lambda: lib.open(path, key=key)))
    if hasattr(lib, "open_from_bytes"):
        data = open(path, "rb").read()
        calls.append(("python NativeLibrary.open_from_bytes", lambda: lib.open_from_bytes(data)))
    for entry, call in calls:
        try:
            db = call()
            print("RESULT\t%s\t%s\tok\t" % (name, entry))
            try: db.close()
            except Exception: pass
        except EmbeddedError as error:
            print("RESULT\t%s\t%s\terr\t%s: %s" % (name, entry, error.code, str(error)))
"""

NODE_PROBE = r"""
const [,, indexPath, libraryPath, addonPath, keyHex, ...specs] = process.argv;
const { NativeLibrary } = await import(new URL("file:///" + indexPath.replace(/\\/g, "/")));
const lib = new NativeLibrary({ libraryPath, addonPath });
for (const spec of specs) {
  const at = spec.indexOf("=");
  const name = spec.slice(0, at), path = spec.slice(at + 1);
  for (const [entry, call] of [["node NativeLibrary.open", () => lib.open(path)]]) {
    try {
      const db = await call();
      console.log(`RESULT\t${name}\t${entry}\tok\t`);
      try { await db.close(); } catch {}
    } catch (error) {
      console.log(`RESULT\t${name}\t${entry}\terr\t${error.code ?? ""}: ${error.message}`);
    }
  }
}
await lib.close?.();
process.exit(0);
"""


def node_headers() -> Path | None:
    """Locally cached node-gyp dev dir (headers + import lib) for an N-API (v8)
    addon build; `--target=<cached version>` makes node-gyp use it offline."""
    base = Path(os.environ.get("LOCALAPPDATA", Path.home())) / "node-gyp" / "Cache"
    candidates = sorted(path for path in base.glob("*") if (path / "include" / "node" / "node_api.h").is_file()) if base.is_dir() else []
    return candidates[-1] if candidates else None


def build_node_addon(rev: str, source: Path) -> Path:
    node_gyp = ROOT / "bindings" / "node" / "node_modules" / "node-gyp" / "bin" / "node-gyp.js"
    headers = node_headers()
    if not node_gyp.is_file() or headers is None:
        raise RuntimeError("node-gyp or cached Node headers unavailable offline")
    here = source / "bindings" / "node"
    run_cmd(["node", str(node_gyp), "rebuild", f"--target={headers.name}"], cwd=here)
    addon = here / "build" / "Release" / "vlite_node.node"
    if not addon.is_file():
        raise RuntimeError(f"addon not produced at {addon}")
    return addon


def parse(output: str) -> tuple[list[tuple[str, str, str, str]], list[str]]:
    results, published = [], []
    for line in output.splitlines():
        parts = line.split("\t")
        if parts[0] == "RESULT" and len(parts) >= 5:
            results.append((parts[1], parts[2], parts[3], parts[4]))
        elif parts[0] == "PUBLISHED":
            published.append("\t".join(parts[1:]))
    return results, published


def classify(outcome: str, detail: str) -> str:
    if outcome == "ok":
        return "ACCEPTED"
    for pattern, label in (
        (r"UnsupportedFeature\(4\)|unsupported feature flags 0x0004", "UnsupportedFeature(4)"),
        (r"UnsupportedVersion\(5\)|unsupported format version 5", "UnsupportedVersion(5)"),
        (r"ReplicaDiverged", "ReplicaDiverged"),
    ):
        if re.search(pattern, detail):
            return label
    return "OtherError: " + detail[:120]


def expected(rev: str, entry: str) -> set[str]:
    if rev in PRE_V5_REVS:
        return {"UnsupportedVersion(5)"}
    if entry in ("ReplicaFollower::apply", "ReplicaFollower::apply_file"):
        # Rejected by the follower's header/lineage comparison before replay.
        return {"ReplicaDiverged"}
    return {"UnsupportedFeature(4)"}


def run_revisions(args: argparse.Namespace) -> int:
    work = Path(args.work).resolve()
    work.mkdir(parents=True, exist_ok=True)
    fixture_dir = work / "fixtures"
    fixture_dir.mkdir(exist_ok=True)
    generated = fixtures()
    specs = {}
    for name in ("v5_graph_plain", "v5_graph_timestamps", "v5_control_plain"):
        (fixture_dir / f"{name}.vlite").write_bytes(generated[name])
    specs["plain"] = fixture_dir / "v5_graph_plain.vlite"
    specs["timestamps"] = fixture_dir / "v5_graph_timestamps.vlite"
    graph_frame_path = fixture_dir / "graph_frame_seq2.bin"
    graph_frame_path.write_bytes(graph_frame(2))

    toolchain = {
        "rustc": run_cmd(["rustc", "-V"], env=cargo_env()).stdout.strip(),
        "cargo": run_cmd(["cargo", "-V"], env=cargo_env()).stdout.strip(),
        "python": sys.version.split()[0],
    }
    node = shutil.which("node")
    if node:
        toolchain["node"] = run_cmd(["node", "--version"]).stdout.strip()

    revs = args.revs or DEFAULT_REVS
    builds, rows, failures = {}, [], []
    # HEAD first: it creates the encrypted base file (public API only).
    for rev in revs:
        sha = resolve(rev)
        source = extract(rev, sha, work)
        info = {"sha": sha, "source": str(source)}
        builds[rev] = info
        try:
            probe, dropped = build_probe(rev, source, work)
            info["probe"] = "built"
            info["entry_points_absent_in_revision"] = dropped
        except RuntimeError as error:
            info["probe"] = f"BUILD FAILED: {error}"
            failures.append(f"{rev}: probe build failed")
            continue
        if "encrypted" not in specs:
            encrypted_base = fixture_dir / f"encrypted_base_{rev}.vlite"
            encrypted_base.unlink(missing_ok=True)
            made = run_cmd([str(probe), "make-encrypted", str(encrypted_base)], check=False)
            if made.returncode == 0:
                data = encrypted_base.read_bytes()
                flags = struct.unpack_from("<H", data, 26)[0]
                assert flags == FLAG_ENCRYPTED, flags
                path = fixture_dir / "v5_graph_encrypted.vlite"
                path.write_bytes(set_header_flags(data, flags | FLAG_GRAPH))
                specs["encrypted"] = path
                info["encrypted_fixture_source"] = f"created by this revision ({rev}) public API, then FLAG_GRAPH set"
        scratch = work / f"scratch-{rev}"
        if scratch.exists():
            shutil.rmtree(scratch)
        env = dict(os.environ, PROBE_FOLLOWER_BASE=str(fixture_dir / "v5_control_plain.vlite"), PROBE_GRAPH_FRAME=str(graph_frame_path))
        result = run_cmd([str(probe), "check", str(scratch)] + [f"{n}={p}" for n, p in specs.items()], env=env, check=False)
        if result.returncode != 0:
            failures.append(f"{rev}: probe crashed ({result.returncode}): {result.stderr[-800:]}")
        results, published = parse(result.stdout)
        for item in published:
            failures.append(f"{rev}: output published by rejecting entry point: {item}")
        if not args.skip_bindings:
            try:
                dll = build_ffi(rev, source, work)
                py = run_cmd([sys.executable, "-c", PY_PROBE, str(source / "bindings" / "python"), str(dll), KEY.hex()] + [f"{n}={p}" for n, p in specs.items()], check=False)
                if py.returncode != 0:
                    failures.append(f"{rev}: python probe crashed: {py.stderr[-800:]}")
                results += parse(py.stdout)[0]
                info["c_abi_python"] = "built"
            except RuntimeError as error:
                info["c_abi_python"] = f"UNAVAILABLE: {str(error)[:300]}"
                failures.append(f"{rev}: C ABI/Python build unavailable")
            if node:
                try:
                    addon = build_node_addon(rev, source)
                    script = work / "node_probe.mjs"
                    script.write_text(NODE_PROBE, encoding="utf-8")
                    nd = run_cmd(["node", str(script), str(source / "bindings" / "node" / "index.js"), str(dll), str(addon), KEY.hex()] + [f"{n}={p}" for n, p in specs.items()], check=False)
                    if nd.returncode != 0:
                        failures.append(f"{rev}: node probe crashed: {nd.stderr[-800:]}")
                    results += parse(nd.stdout)[0]
                    info["node"] = "built"
                except (RuntimeError, NameError) as error:
                    info["node"] = f"UNAVAILABLE: {str(error)[:300]}"
                    failures.append(f"{rev}: Node build unavailable offline")
        for fixture, entry, outcome, detail in results:
            label = classify(outcome, detail)
            ok = label in expected(rev, entry)
            rows.append({"rev": rev, "fixture": fixture, "entry": entry, "result": label, "expected": sorted(expected(rev, entry)), "pass": ok})
            if not ok:
                failures.append(f"{rev} {fixture} {entry}: {label} (expected {sorted(expected(rev, entry))})")

    summary = {}
    for row in rows:
        key = (row["rev"], row["result"])
        summary[key] = summary.get(key, 0) + 1
    print(f"toolchain: {json.dumps(toolchain)}")
    for rev in revs:
        info = builds.get(rev, {})
        print(f"\n## {rev} ({info.get('sha', '?')[:12]}) probe={info.get('probe')} c_abi_python={info.get('c_abi_python', 'skipped')} node={info.get('node', 'skipped')}")
        if info.get("entry_points_absent_in_revision"):
            print("   absent in revision (not probed): " + "; ".join(info["entry_points_absent_in_revision"]))
        print(f"   {'fixture':<11} {'entry point':<46} {'result':<24} pass")
        for row in (r for r in rows if r["rev"] == rev):
            print(f"   {row['fixture']:<11} {row['entry']:<46} {row['result']:<24} {'yes' if row['pass'] else 'NO'}")
    print("\nsummary:")
    for (rev, label), count in sorted(summary.items()):
        print(f"   {rev:<8} {label:<24} {count}")
    if args.json:
        Path(args.json).write_text(json.dumps({"toolchain": toolchain, "builds": builds, "rows": rows, "failures": failures}, indent=2), encoding="utf-8")
    if failures:
        print("\nFAILURES:")
        for failure in failures:
            print("   " + failure)
        return 1
    print(f"\nPASS: {len(rows)} entry-point probes matched DO-001 expectations")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("fixtures")
    run = sub.add_parser("run")
    run.add_argument("--revs", nargs="*")
    run.add_argument("--work", default=str(Path(tempfile.gettempdir()) / "vlite-graph-compat"))
    run.add_argument("--skip-bindings", action="store_true")
    run.add_argument("--json")
    args = parser.parse_args()
    if args.command == "fixtures":
        write_fixtures()
        return 0
    return run_revisions(args)


if __name__ == "__main__":
    sys.exit(main())
