#!/usr/bin/env python3
"""REG-001 public API item list (feature-agent-graph EPIC-001 ITEM-005).

Runs `cargo doc --no-deps -p vlite` (stable toolchain, no extra dependencies)
and parses the rustdoc item index `<target>/doc/vlite/all.html` into a sorted
list of `<kind> <path>` lines.

Subcommands
-----------
baseline [--rev 347b01d] [--features LIST] [--output PATH]
    Builds docs for the exact baseline commit, extracted with `git archive`
    into an isolated temporary directory (offline, own target dir), and
    writes the list (default: tests/fixtures/api_surface/vlite-default.txt).

check [--features LIST] [--baseline PATH]
    Builds docs for the working tree (target/api-surface) and compares with
    the baseline list; prints additions/removals and exits 1 on any
    difference. With `graph` in --features (C-2), additions under
    `vlite::property_graph::` are reported as ALLOWED and do not fail; any
    other addition, and every removal, still fails.

`all.html` lists items (structs, enums, functions, traits, macros, constants,
type aliases, ...) but not methods or fields; signature compatibility of
existing items is covered by REG-002 (existing tests compile unchanged).
"""

from __future__ import annotations

import argparse
import html
import re
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from graph_compat_check import cargo_env, extract, resolve, run_cmd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BASELINE = ROOT / "tests" / "fixtures" / "api_surface" / "vlite-default.txt"
GRAPH_PREFIX = "vlite::property_graph::"
SECTION = re.compile(r'<h3 id="([a-z-]+)">')
LINK = re.compile(r'<a href="([^"]+)">(.*?)</a>')


def parse(all_html: str) -> list[str]:
    items: set[str] = set()
    parts = SECTION.split(all_html)
    for kind, body in zip(parts[1::2], parts[2::2]):
        listing = body.split('<ul class="all-items">', 1)
        if len(listing) != 2:
            continue
        for href, text in LINK.findall(listing[1].split("</ul>", 1)[0]):
            name = html.unescape(re.sub(r"<[^>]+>", "", text))
            items.add(f"{kind} vlite::{name}")
    if not items:
        raise SystemExit("no items parsed from all.html")
    return sorted(items)


def build(source: Path, target: Path, features: str) -> list[str]:
    command = ["cargo", "doc", "--no-deps", "--offline", "--locked", "--quiet", "-p", "vlite", "--target-dir", str(target)]
    if features:
        command += ["--features", features]
    run_cmd(command, cwd=source, env=cargo_env())
    return parse((target / "doc" / "vlite" / "all.html").read_text(encoding="utf-8"))


def toolchain() -> str:
    return run_cmd(["rustdoc", "--version"], env=cargo_env()).stdout.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    baseline = commands.add_parser("baseline")
    baseline.add_argument("--rev", default="347b01d")
    baseline.add_argument("--features", default="")
    baseline.add_argument("--output", default=str(DEFAULT_BASELINE))
    baseline.add_argument("--work")
    check = commands.add_parser("check")
    check.add_argument("--features", default="")
    check.add_argument("--baseline", default=str(DEFAULT_BASELINE))
    args = parser.parse_args()

    if args.command == "baseline":
        work = Path(args.work or Path(tempfile.gettempdir()) / "vlite-graph-baseline")
        work.mkdir(parents=True, exist_ok=True)
        sha = resolve(args.rev)
        source = extract(args.rev, sha, work)
        items = build(source, work / f"target-doc-{args.rev}", args.features)
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        header = (
            f"# vlite public item list (rustdoc all.html) for {sha}, features: [{args.features}]\n"
            f"# {toolchain()}\n# Generated by: python scripts/api_surface.py baseline\n"
        )
        output.write_text(header + "\n".join(items) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {len(items)} items to {output}")
        return 0

    expected = [
        line
        for line in Path(args.baseline).read_text(encoding="utf-8").splitlines()
        if line and not line.startswith("#")
    ]
    actual = build(ROOT, ROOT / "target" / "api-surface", args.features)
    removed = sorted(set(expected) - set(actual))
    added = sorted(set(actual) - set(expected))
    allowed: list[str] = []
    if "graph" in re.split(r"[,\s]+", args.features.strip()):
        allowed = [item for item in added if item.split(" ", 1)[1].startswith(GRAPH_PREFIX)]
        added = [item for item in added if item not in allowed]
    for item in removed:
        print(f"REMOVED {item}")
    for item in allowed:
        print(f"ALLOWED {item}")
    for item in added:
        print(f"ADDED   {item}")
    if removed or added:
        print(f"FAIL: public API item list differs from {args.baseline}")
        return 1
    suffix = f", {len(allowed)} additions under {GRAPH_PREFIX} allowed by C-2" if allowed else ""
    print(f"PASS: {len(actual)} public items match the baseline{suffix} ({toolchain()})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
